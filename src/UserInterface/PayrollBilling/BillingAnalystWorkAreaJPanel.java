    private void generateSelectedInvoice() {
        if (!"requests".equals(currentView)) {
            JOptionPane.showMessageDialog(this, "Please view Billing Requests first.");
            return;
        }

        int row = tblMain.getSelectedRow();

        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Please select a billing request first.");
            return;
        }

        Object selectedId = tblMain.getValueAt(row, 0);
        BillingRequest request = findBillingRequestById(selectedId);

        if (request == null) {
            JOptionPane.showMessageDialog(this, "Could not find the selected billing request.");
            return;
        }

        if (request.getInvoice() != null) {
            JOptionPane.showMessageDialog(this, "Invoice has already been generated for this request.");
            return;
        }

        try {
            Invoice invoice = request.processBilling();
            Organization hrOrg = NetworkUtils.findOrganizationByName(
                    network,
                    "Client Enterprise",
                    "Human Resources Organization"
            );

            if (hrOrg != null) {
                hrOrg.getWorkQueue().addWorkOrder(request);
            } else {
                showMessage("Invoice generated locally (HR Organization not found).");
            }
            if (request.getBillingRecord() != null
                    && !module.getBillingRecords().contains(request.getBillingRecord())) {
                module.getBillingRecords().add(request.getBillingRecord());
            }

            if (invoice != null && !module.getInvoices().contains(invoice)) {
                module.getInvoices().add(invoice);
            }

            JOptionPane.showMessageDialog(
                    this,
                    "Invoice generated. Client invoice total: " + money(invoice.getInvoiceTotal())
            );

            showInvoices();

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "Billing Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

    private void showBillingRecords() {
        currentView = "records";

        DefaultTableModel model = new DefaultTableModel(
                new String[]{"Billing ID", "Contractor", "Hours", "Client Bill Rate", "Client Invoice Total", "Status"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (BillingRecord record : module.getBillingRecords()) {
            model.addRow(new Object[]{
                record.getBillingId(),
                contractorName(record.getAssignment()),
                record.getHoursBilled(),
                money(record.getBillRate()),
                money(record.getInvoiceAmount()),
                record.getBillingStatus()
            });
        }

        tblMain.setModel(model);
    }

    private void showInvoices() {
        currentView = "invoices";

        DefaultTableModel model = new DefaultTableModel(
                new String[]{"Invoice ID", "Timecard ID", "Hours", "Total", "Invoice Date", "Due Date", "Status"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (Invoice invoice : module.getInvoices()) {
            model.addRow(new Object[]{
                invoice.getInvoiceId(),
                invoice.getTimeCardId(),
                invoice.getTotalHours(),
                money(invoice.getInvoiceTotal()),
                invoice.getInvoiceDate(),
                invoice.getDueDate(),
                invoice.getInvoiceStatus()
            });
        }

        tblMain.setModel(model);
    }

    private void showBillingReport() {
        currentView = "report";

        PayrollReport report = new PayrollReport();

        report.generateSummary(
                module.getPayrollRecords(),
                module.getBillingRecords(),
                module.getInvoices(),
                module.getPayrollRequests()
        );

        DefaultTableModel model = new DefaultTableModel(
                new String[]{"Metric", "Value"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        model.addRow(new Object[]{"Total Billing Amount", money(report.getTotalBillingAmount())});
        model.addRow(new Object[]{"Billing Records Processed", report.getBillingRecordsProcessed()});
        model.addRow(new Object[]{"Invoices Generated", report.getInvoicesGenerated()});
        model.addRow(new Object[]{"Total Contractor Hours", report.getTotalContractorHours()});
        model.addRow(new Object[]{"Total Payroll Amount", money(report.getTotalPayrollAmount())});

        tblMain.setModel(model);
    }

    private BillingRequest findBillingRequestById(Object selectedId) {
        if (selectedId == null) {
            return null;
        }

        int requestId;

        try {
            requestId = Integer.parseInt(selectedId.toString());
        } catch (NumberFormatException ex) {
            return null;
        }

        for (BillingRequest request : module.getBillingRequests()) {
            if (request.getWorkOrderId() == requestId) {
                return request;
            }
        }

        return null;
    }

    private void refreshCurrentView() {
        if ("records".equals(currentView)) {
            showBillingRecords();
        } else if ("invoices".equals(currentView)) {
            showInvoices();
        } else if ("report".equals(currentView)) {
            showBillingReport();
        } else {
            showBillingRequests();
        }
    }

    private String contractorName(ContractorAssignment assignment) {
        if (assignment == null) {
            return "N/A";
        }

        Contractor contractor = assignment.getContractor();
        return contractor == null ? "N/A" : contractor.getFullName();
    }

    private String money(BigDecimal amount) {
        return amount == null
                ? "$0.00"
                : "$" + amount.setScale(2, java.math.RoundingMode.HALF_UP).toString();
    }

