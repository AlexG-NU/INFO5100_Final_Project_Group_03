    private void showBillingRequests() {
        currentView = "requests";

        DefaultTableModel model = new DefaultTableModel(
                new String[]{"Request ID", "Contractor", "Hours", "Status", "Invoice"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (BillingRequest request : module.getBillingRequests()) {
            model.addRow(new Object[]{
                request.getWorkOrderId(),
                contractorName(request.getAssignment()),
                request.getHoursBilled(),
                request.getStatus(),
                request.getInvoice() == null ? "Not Generated" : request.getInvoice().getInvoiceId()
            });
        }

        tblMain.setModel(model);
    }
    
